import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = text => ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const uri = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const sharedUri = uri(compile(await readFile(new URL('../lib/shooting.ts', import.meta.url), 'utf8')));
const engineUri = uri(compile(await readFile(new URL('../supabase/functions/_shared/agent.ts', import.meta.url), 'utf8')).replace("'../../../lib/shooting.ts'", JSON.stringify(sharedUri)));
const edge = compile(await readFile(new URL('../supabase/functions/shooting-agent/index.ts', import.meta.url), 'utf8')).replace("'../_shared/agent.ts'", JSON.stringify(engineUri)).replace("'../../../lib/shooting.ts'", JSON.stringify(sharedUri));
const env = new Map([['SUPABASE_URL','https://test-project.supabase.co'],['SUPABASE_PUBLISHABLE_KEYS',JSON.stringify({ default: 'sb_publishable_test_only' })]]);
let handler;
globalThis.Deno = { env: { get: name => env.get(name) }, serve: fn => { handler = fn; } };
await import(uri(edge));
const send = (path = '', init = {}) => handler(new Request('https://test-project.supabase.co/functions/v1/shooting-agent' + path, init));
let count = 0;
globalThis.fetch = async () => { count++; throw new Error('Unexpected network'); };
assert.equal((await send()).status, 401);
assert.equal(count, 0, 'Unsigned requests rejected before any data access');
assert.equal((await send('', { method: 'OPTIONS' })).status, 200);
const authHeaders = { Authorization: 'Bearer synthetic-test-session', 'Content-Type': 'application/json' };
globalThis.fetch = async (url, init) => {
  assert.equal(new Headers(init.headers).get('Authorization'), authHeaders.Authorization);
  assert.equal(new Headers(init.headers).get('apikey'), 'sb_publishable_test_only');
  assert.ok(url.endsWith('/auth/v1/user'));
  return Response.json({ id: 'test-user' });
};
const status = await send('', { headers: authHeaders });
assert.equal((await status.json()).enabled, false);
const unavailable = await send('', { method: 'POST', headers: authHeaders, body: '{}' });
assert.equal(unavailable.status, 503);
assert.equal((await unavailable.json()).code, 'MODEL_NOT_CONFIGURED');
env.set('MODEL_CHAT_COMPLETIONS_URL','https://model.example.invalid/chat/completions'); env.set('MODEL_API_KEY','synthetic-test-key'); env.set('MODEL_NAME','test-tool-model'); env.set('MODEL_PROVIDER_LABEL','Test Provider');
assert.equal((await send('', { method: 'POST', headers: { ...authHeaders, Origin: 'https://untrusted.example' }, body: '{}' })).status, 403);
assert.equal((await send('', { method: 'POST', headers: authHeaders, body: JSON.stringify({ projectId: '11111111-1111-1111-1111-111111111111', message: '拍摄', consent: false }) })).status, 400);
let dataReads = 0;
globalThis.fetch = async (url, init) => {
  if (url.endsWith('/auth/v1/user')) return Response.json({ id: 'test-user' });
  dataReads++;
  assert.equal(new Headers(init.headers).get('Authorization'), authHeaders.Authorization, 'Forward only the user JWT, never admin credentials');
  return Response.json([]);
};
const missing = await send('', { method: 'POST', headers: authHeaders, body: JSON.stringify({ projectId: '11111111-1111-1111-1111-111111111111', message: '拍摄', consent: true }) });
assert.equal(missing.status, 404);
assert.equal(dataReads, 1, 'Unowned project rejected before model or conversation writes');
console.log('Edge handler: auth, CORS, provider disclosure, missing-model 503, consent and user-scoped access checks passed with synthetic fixtures. No live model calls.');
