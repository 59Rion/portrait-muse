import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = text => ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const uri = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const sharedUri = uri(compile(await readFile(new URL('../lib/shooting.ts', import.meta.url), 'utf8')));
const { emptyBrief, emptyPlan, parseBrief, parsePlan, checkPlan, rankReferences } = await import(sharedUri);
const agentSource = compile(await readFile(new URL('../supabase/functions/_shared/agent.ts', import.meta.url), 'utf8')).replace("'../../../lib/shooting.ts'", JSON.stringify(sharedUri));
const { runAgent } = await import(uri(agentSource));
const brief = { ...emptyBrief, purpose: '个人写真', location: '室内窗边', equipment: '只有手机，没有三脚架，没有补光灯', team: '独自拍摄', durationMinutes: 30 };
const plan = { ...emptyPlan, goal: '室内清冷人像', alternatives: '光线不足则移至明亮窗边', shots: [{ name: '窗边半身', minutes: 10, instructions: '靠窗侧身看向镜头' }], referenceIds: ['ref-a'] };
assert.equal(parseBrief(brief).team, '独自拍摄');
assert.throws(() => parseBrief({ ...brief, durationMinutes: -1 }));
assert.throws(() => parsePlan({ ...plan, shots: [{ name: '', minutes: 0 }] }));
assert.throws(() => parsePlan({ ...plan, referenceIds: ['bad?injection'] }));
assert.equal(checkPlan(brief, plan).length, 0);
assert.equal(checkPlan(brief, { ...plan, lighting: '安排助手持补光灯', composition: '更换镜头 85mm，安装三脚架', shots: [{ name: '镜头', minutes: 45, instructions: '' }] }).filter(w => w.includes('冲突')).length, 5);
assert.equal(checkPlan(brief, { ...plan, lighting: '无需补光灯', composition: '不使用三脚架' }).length, 0);
const refs = [{ id: 'ref-a', title: '窗边', tags: ['清冷'], description: '自然光', summary: '' }, { id: 'ref-b', title: '海边', tags: ['少女'], description: '', summary: '' }];
assert.deepEqual(rankReferences(refs, '清冷 室内').map(r => r.id), ['ref-a']);
assert.equal(rankReferences(refs, '不存在').length, 0);
let readCount = 0;
const store = { project: async () => ({ brief, latestPlan: plan }), search: async q => rankReferences(refs, q), detail: async id => { readCount++; return refs.find(r => r.id === id) || null; } };
const call = (name, args = {}) => ({ id: `call-${Math.random()}`, type: 'function', function: { name, arguments: JSON.stringify(args) } });
const finish = (extra = {}) => call('present_result', { reply: '草稿待你确认', questions: [], brief: null, recommendations: [{ referenceId: 'ref-a', reason: '文字和标签匹配窗边清冷主题' }], ...extra });
const sequence = [call('get_project_details'), call('search_references', { query: '清冷' }), call('get_reference_details', { referenceId: 'ref-a' }), call('save_shooting_plan', { plan }), finish()];
const output = await runAgent(async () => ({ tool_calls: [sequence.shift()] }), store, { message: '找参考并拟定方案' });
assert.equal(output.plan.goal, plan.goal);
assert.equal(readCount, 1);
assert.ok(output.trace.some(t => t.tool === 'check_constraints'));
assert.ok(output.trace.at(-2).detail.includes('未写入'));
// A failed/forged reference never becomes an approved source or a saved draft.
let round = 0;
const rejected = await runAgent(async messages => {
  round++;
  if (round === 1) return { tool_calls: [call('get_project_details')] };
  if (round === 2) return { tool_calls: [call('get_reference_details', { referenceId: 'other-user-ref' })] };
  if (round === 3) return { tool_calls: [call('save_shooting_plan', { plan: { ...plan, referenceIds: ['other-user-ref'] } })] };
  if (round === 4) return { tool_calls: [finish({ recommendations: [{ referenceId: 'other-user-ref', reason: '伪造来源' }] })] };
  assert.ok(messages.some(m => m.role === 'tool' && m.content.includes('error')));
  return { tool_calls: [finish({ recommendations: [], questions: ['没有找到合适资料，要先上传参考吗？'] })] };
}, store, { message: '找参考' });
assert.equal(rejected.plan, null);
assert.equal(rejected.recommendations.length, 0);
assert.equal(rejected.trace.filter(t => t.status === 'error').length, 3);
// Model chooses follow-up questions instead of forcing the fixed search→plan workflow.
const clarifyCalls = [call('get_project_details'), finish({ brief: emptyBrief, recommendations: [], questions: ['使用手机还是相机？'] })];
const clarify = await runAgent(async () => ({ tool_calls: [clarifyCalls.shift()] }), { ...store, project: async () => ({ brief: emptyBrief }) }, { message: '帮我拍一组' });
assert.equal(clarify.plan, null);
assert.equal(clarify.questions.length, 1);
assert.ok(!clarify.trace.some(t => t.tool === 'search_references'));
await assert.rejects(() => runAgent(async () => ({ content: '我已经保存了' }), store, { message: '保存' }), /未返回可校验/);
console.log('Workspace: validation, rule conflicts, retrieval, autonomous tool choice, draft-only writes, forged-source rejection and follow-up checks passed. Model calls are mocked, not live.');
